"""
handlers/common.py — ОБЩИЕ ОБРАБОТЧИКИ: команда /help и ответ "не понимаю".

Этот роутер подключается в main.py ПОСЛЕДНИМ. Это важно: обработчик fallback
ловит вообще любое сообщение, поэтому если поставить его раньше — он "перехватит"
сообщения, предназначенные другим роутерам.
"""

# Router  — "роутер": контейнер для группы обработчиков. Каждый файл handlers/ создаёт свой.
from aiogram import Router
# Command — фильтр: "сообщение является командой /help".
from aiogram.filters import Command
# Message — тип "входящее сообщение" (текст, контакт, фото и т.д.).
from aiogram.types import Message

# Создаём роутер. name — просто имя для отладки. В main.py: dp.include_router(common.router)
router = Router(name="common")


# @router.message(...) — ДЕКОРАТОР. Он регистрирует функцию как обработчик сообщений.
# В скобках — фильтр: функция вызовется, только если пришла команда /help.
# message: Message — aiogram сам передаёт сюда объект пришедшего сообщения.
# -> None — функция ничего не возвращает.
@router.message(Command("help"))
async def cmd_help(message: Message) -> None:
    # message.answer(...) — отправить ответ в тот же чат.
    await message.answer(
        "Доступные действия — используйте кнопки меню:\n"
        "💊 Каталог — посмотреть товары по категориям\n"
        "🛒 Корзина — текущая корзина и оформление заказа\n"
        "📦 Мои заказы — история заказов\n"
        "👤 Профиль — ваши данные\n\n"
        "Если меню не видно, отправьте /start."
    )


# @router.message() БЕЗ фильтров — ловит ЛЮБОЕ сообщение.
# Срабатывает, только если ни один обработчик выше (во всех роутерах) не подошёл.
@router.message()
async def fallback(message: Message) -> None:
    await message.answer("Не понимаю эту команду. Воспользуйтесь кнопками меню или /help.")
